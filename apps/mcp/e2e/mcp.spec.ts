test('initial loading, first creation and last deletion use one add entry', async ({ page }) => {
  const fixture = await installHostFixture(page, { holdInitialList: true })
  await page.goto('/')
  await expect(page.getByRole('status')).toHaveText('正在读取服务…')
  await expect(page.getByRole('button', { name: '添加服务', exact: true })).toBeDisabled()
  await expect(page.getByRole('heading', { name: '添加第一个 MCP 服务' })).toHaveCount(0)
  fixture.releaseList()
  await expect(page.getByRole('heading', { name: '添加第一个 MCP 服务' })).toBeVisible()
  await expect(page.getByRole('button', { name: '添加服务', exact: true })).toHaveCount(1)
  await expect(page.getByRole('textbox', { name: '搜索服务' })).toBeVisible()
  await expect(page.getByRole('complementary')).toHaveCount(0)
  await page.getByRole('button', { name: '添加服务', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '添加 MCP 服务' })
  await dialog.getByLabel('服务名称').fill('first-service')
  await dialog.getByLabel('服务地址').fill('https://example.com/mcp')
  await dialog.getByRole('button', { name: '创建连接' }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'first-service', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '添加服务', exact: true })).toHaveCount(1)
  fixture.failNextList()
  await page.getByRole('button', { name: '刷新服务列表' }).click()
  await expect(page.getByRole('alert')).toContainText('无法读取连接')
  await expect(page.getByRole('heading', { name: 'first-service', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '删除 first-service', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '删除', exact: true }).click()
  await expect(page.getByRole('heading', { name: '添加第一个 MCP 服务' })).toBeVisible()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '添加服务', exact: true })).toHaveCount(1)
  await expect(page.getByRole('complementary')).toHaveCount(0)
})


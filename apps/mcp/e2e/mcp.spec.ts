const browserTools = [
  { name: 'browser_navigate', description: 'Navigate to a URL', disabled: false },
  { name: 'browser_click', description: 'Click an element', disabled: false },
]
const browserServers = () => [{ name: 'playwright-cdp', enabled: true, updatedAt: 1, config: { type: 'stdio' as const, command: 'fixture' } }]
const service = (page: Page, name = 'playwright-cdp') => page.locator('.managed-service').filter({ has: page.getByRole('heading', { name, exact: true }) })

test('explicit connection checks show progress and keep management actions disabled until complete', async ({ page }) => {
  const fixture = await installHostFixture(page, { servers: browserServers(), tools: browserTools, holdInspection: true })
  await page.goto('/')
  const connection = service(page)
  await expect(connection.getByText('未检查', { exact: true })).toBeVisible()
  expect(fixture.calls).toEqual(['servers.list'])
  await connection.getByRole('button', { name: '检查连接' }).click()
  await expect(page.getByRole('status')).toContainText('正在检查连接')
  await expect(connection.getByRole('checkbox')).toBeDisabled()
  await expect(connection.getByRole('button', { name: '编辑 playwright-cdp' })).toBeDisabled()
  await expect(page.getByRole('button', { name: '添加服务', exact: true })).toBeDisabled()
  fixture.releaseInspection()
  await expect(connection.getByText('检查通过', { exact: true })).toBeVisible()
  await expect(page.getByRole('status')).toHaveCount(0)
  await expect(connection.getByRole('checkbox')).toBeEnabled()
  expect(fixture.calls.filter(method => method === 'servers.inspect')).toHaveLength(1)
  // The Host detail renders the tool catalog; this page only manages connections.
  await expect(page.getByRole('textbox', { name: '搜索工具' })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'browser_navigate' })).toHaveCount(0)
})

test('enabling and editing preserve tool exclusions without automatically connecting', async ({ page }) => {
  const fixture = await installHostFixture(page, { servers: browserServers().map(server => ({ ...server, enabled: false, config: { ...server.config, disabledTools: ['browser_click'] } })) })
  await page.goto('/')
  await expect(page.getByRole('checkbox', { name: '启用 playwright-cdp' })).not.toBeChecked()
  await page.getByRole('checkbox', { name: '启用 playwright-cdp' }).click()
  await expect(page.getByRole('checkbox', { name: '启用 playwright-cdp' })).toBeChecked()
  await page.getByRole('button', { name: '编辑 playwright-cdp', exact: true }).click()
  const edit = page.getByRole('dialog', { name: '编辑连接' })
  await edit.getByLabel('启动命令').fill('updated-fixture')
  await expect.poll(() => fixture.viewStates.at(-1)?.dirty).toBe(true)
  await edit.getByRole('button', { name: '保存更改' }).click()
  await expect(edit).toHaveCount(0)
  await expect(service(page)).toContainText('updated-fixture')
  await expect.poll(() => fixture.viewStates.at(-1)).toEqual({ dirty: false, busy: false })
  expect(fixture.requests.find(request => request.method === 'servers.save')?.input).toMatchObject({
    name: 'playwright-cdp', previousName: 'playwright-cdp', enabled: true,
    config: { type: 'stdio', command: 'updated-fixture', disabledTools: ['browser_click'] },
  })
  expect(fixture.calls).not.toContain('servers.inspect')
})

test('cancelled connection checks ignore late responses and can be retried', async ({ page }) => {
  const fixture = await installHostFixture(page, { servers: browserServers(), tools: browserTools, holdInspection: true })
  await page.goto('/')
  await service(page).getByRole('button', { name: '检查连接' }).click()
  await expect(page.getByRole('status')).toContainText('正在检查连接')
  await page.getByRole('status').getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText(/abort|cancel/i)
  await expect(page.getByRole('status')).toHaveCount(0)
  await expect.poll(fixture.cancellations).toBeGreaterThan(0)
  fixture.releaseInspection()
  await expect.poll(fixture.completedInspections).toBe(1)
  await expect(service(page).getByText('未检查', { exact: true })).toBeVisible()
  await service(page).getByRole('button', { name: '检查连接' }).click()
  await expect(service(page).getByText('检查通过', { exact: true })).toBeVisible()
  await expect(page.getByRole('alert')).toHaveCount(0)
  expect(fixture.calls.filter(method => method === 'servers.inspect')).toHaveLength(2)
})

test('failed connection checks show the Host error and support retry', async ({ page }) => {
  const fixture = await installHostFixture(page, { servers: browserServers(), inspectError: '连接失败，请重试。' })
  await page.goto('/')
  await service(page).getByRole('button', { name: '检查连接' }).click()
  await expect(service(page).getByRole('alert')).toContainText('连接失败，请重试。')
  fixture.recoverInspection()
  await service(page).getByRole('button', { name: '检查连接' }).click()
  await expect(service(page).getByText('检查通过', { exact: true })).toBeVisible()
  await expect(page.getByRole('alert')).toHaveCount(0)
  expect(fixture.calls.filter(method => method === 'servers.inspect')).toHaveLength(2)
})

test('remote connections support authorization and confirmed credential clearing', async ({ page }) => {
  const fixture = await installHostFixture(page, { servers: [{ name: 'remote', enabled: true, updatedAt: 1, config: { type: 'http', url: 'https://example.com/mcp' }, check: { state: 'needs-auth', tools: [], checkedAt: 1 } }] })
  await page.goto('/')
  const connection = service(page, 'remote')
  await expect(connection.getByText('需要授权', { exact: true })).toBeVisible()
  await connection.getByRole('button', { name: '授权', exact: true }).click()
  await expect(connection.getByText('已授权', { exact: true })).toBeVisible()
  page.once('dialog', dialog => dialog.dismiss())
  await connection.getByRole('button', { name: '清除授权', exact: true }).click()
  expect(fixture.calls).not.toContain('auth.clear')
  page.once('dialog', dialog => dialog.accept())
  await connection.getByRole('button', { name: '清除授权', exact: true }).click()
  await expect(connection.getByText('未检查', { exact: true })).toBeVisible()
  expect(fixture.requests.filter(request => request.method.startsWith('auth.'))).toEqual([
    { method: 'auth.start', input: { name: 'remote' } },
    { method: 'auth.clear', input: { name: 'remote' } },
  ])
})


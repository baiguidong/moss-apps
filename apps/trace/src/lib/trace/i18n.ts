export function traceTranslation(key: string, values?: Record<string, string | number>): string {
  const message = messages[key] ?? key
  return message.replace(/\{(\w+)\}/g, (match, name) => String(values?.[name] ?? match))
}

// Stable reference keeps revision polling effects from restarting during render.
export function useTranslation() { return traceTranslation }

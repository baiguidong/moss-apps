// The upstream Electron package contains a platform-neutral core followed by an
// Electron IPC wrapper. Ship that unmodified core for our Node Backend, with the
// matching native assets, instead of the discontinued Node SDK's broken x64 lib.
import fs from 'node:fs/promises'
import { createRequire } from 'node:module'
import path from 'node:path'
const require = createRequire(import.meta.url)
const root = path.dirname(require.resolve('@openim/electron-client-sdk/package.json'))
const pkg = JSON.parse(await fs.readFile(path.join(root, 'package.json'), 'utf8'))
if (pkg.version !== '3.8.3-patch.10') throw new Error('Review the native SDK adapter before upgrading OpenIM')
const original = (await fs.readFile(path.join(root, 'lib/index.es.js'), 'utf8')).replace(/\r\n/g, '\n')
const boundary = original.indexOf('\nclass OpenIMSDKMain {')
if (boundary < 0 || !original.startsWith("import { powerMonitor, ipcMain } from 'electron';\n")) throw new Error('Unsupported upstream OpenIM module layout')
const core = original.slice(original.indexOf('\n') + 1, boundary)
if (/\b(?:powerMonitor|ipcMain|electron)\b/.test(core)) throw new Error('OpenIM core still requires Electron')
const output = `// Generated by scripts/sync-native-sdk.mjs from @openim/electron-client-sdk@${pkg.version}.\n// Upstream MIT license: see native-sdk.LICENSE. Only the Electron wrapper is removed.\n${core}\nexport { OpenIMSDK as default };\n`
const destination = new URL('../src/backend/native-sdk.mjs', import.meta.url)
const license = new URL('../src/backend/native-sdk.LICENSE', import.meta.url)
if (process.argv.includes('--check')) {
  if (await fs.readFile(destination, 'utf8') !== output) throw new Error('Regenerate and review the native SDK adapter')
  if (await fs.readFile(license, 'utf8') !== await fs.readFile(path.join(root, 'LICENSE'), 'utf8')) throw new Error('Native SDK license differs from upstream')
} else {
  await fs.writeFile(destination, output)
  await fs.copyFile(path.join(root, 'LICENSE'), license)
}

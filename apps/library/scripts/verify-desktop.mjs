import assert from 'node:assert/strict'
import { _electron as electron, expect } from '@playwright/test'
import { mkdir, rm, writeFile } from 'node:fs/promises'
import { resolve, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildEmbeddedShell } from './build-embedded-shell.mjs'
const appRoot = fileURLToPath(new URL('..', import.meta.url)), repo = resolve(appRoot, '../..')
const core = process.env.MOSS_CORE_ROOT || resolve(repo, '../moss')
const version = '0.1.1'
const reportDir = join(repo, 'artifacts/moss.library/verification', version)
await mkdir(reportDir, { recursive: true })
const shell = await buildEmbeddedShell(core, join(reportDir, 'embedded-shell'))
process.env.PW_CHROMIUM_ATTACH_TO_OTHER = '1'
const desktop = await electron.launch({ executablePath: process.env.MOSS_TEST_ELECTRON || join(core, 'ui/node_modules/electron/dist/Electron.app/Contents/MacOS/Electron'), args: [join(appRoot, 'scripts/desktop-fixture.cjs')], env: { ...process.env, MOSS_CORE_ROOT: core, MOSS_TEST_NODE: process.env.MOSS_TEST_NODE || process.execPath, MOSS_LIBRARY_TEST_SHELL: shell, MOSS_LIBRARY_ARCHIVE: process.env.MOSS_LIBRARY_ARCHIVE || join(repo, `artifacts/moss.library/${version}/moss.library-${version}.zip`) }, timeout: 60000 })
desktop.process().stderr.on('data', chunk => process.stderr.write(chunk))
desktop.process().stdout.on('data', chunk => process.stdout.write(chunk))
const errors = [], checks = []
let temporary
try {
  const shellPage = await desktop.firstWindow()
  const page = await desktop.waitForEvent('window', { predicate: page => page !== shellPage, timeout: 30000 })
  page.on('pageerror', e => errors.push(e.message))
  await page.waitForURL(url => url.pathname.endsWith('/dist/ui/index.html'))
  temporary = await desktop.evaluate(() => globalThis.libraryFixture.temporary)
  const shot = async name => writeFile(join(reportDir, name), Buffer.from(await desktop.evaluate(() => globalThis.libraryFixture.screenshot()), 'base64'))
  await expect(page.getByText('开始积累你的知识', { exact: true })).toBeVisible()
  checks.push('ZIP install, 5 CRUD tool contributions and no management tools, global search, explicit collection filter, schema rejects projectId, resource resolution, persistent restart, concurrent revision protection, disable/enable')
  await page.getByRole('button', { name: '新建资料集', exact: true }).click()
  let dialog = page.getByRole('dialog', { name: '新建资料集' })
  await dialog.getByRole('textbox', { name: '名称' }).fill('研究笔记')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await page.getByRole('button', { name: '新建文档', exact: true }).click()
  dialog = page.getByRole('dialog', { name: '新建文档' })
  await dialog.getByRole('textbox', { name: '标题' }).fill('迁移设计')
  await dialog.getByRole('textbox', { name: '正文' }).fill('# 通用资料库\n\n不绑定项目或会话，orchid 全库搜索。')
  await shot('editor.png')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('heading', { name: '迁移设计', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '编辑', exact: true }).click()
  dialog = page.getByRole('dialog', { name: '编辑文档' })
  await dialog.getByRole('textbox', { name: '正文' }).fill('新版知识内容 blueberry')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.locator('.document-content')).toHaveText('新版知识内容 blueberry')
  await page.getByRole('button', { name: '打开副本', exact: true }).click()
  await expect.poll(() => desktop.evaluate(() => globalThis.libraryFixture.opened.length)).toBe(1)
  await page.getByRole('button', { name: '关闭文档', exact: true }).click()
  await page.getByRole('button', { name: '导入目录', exact: true }).click()
  dialog = page.getByRole('dialog', { name: '导入资料' })
  await expect(dialog.getByRole('combobox', { name: '保存到资料集' })).toBeVisible()
  await dialog.getByRole('button', { name: '开始导入', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await page.getByRole('textbox', { name: '搜索文档' }).fill('orchid')
  await expect(page.locator('.document-row')).toHaveCount(1)
  await page.locator('.document-row').click()
  await expect(page.locator('.document-content')).toContainText('跨资料集搜索')
  await shot('desktop-search.png')
  checks.push('Real embedded UI: collection creation, note creation and editing, opening managed copy, directory import with hierarchy, FTS search, document reading')
  await page.getByRole('button', { name: '删除文档', exact: true }).click()
  dialog = page.getByRole('dialog', { name: '删除文档' })
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.getByRole('heading', { name: '检索指南', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '删除文档', exact: true }).click()
  await dialog.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(page.locator('.document-row')).toHaveCount(0)
  await page.getByRole('button', { name: /索引任务/ }).click()
  await expect(page.getByRole('heading', { name: '索引任务', exact: true })).toBeVisible()
  await shot('jobs.png')
  await page.evaluate(() => { document.documentElement.dataset.theme = 'dark' })
  await shot('dark.png')
  await desktop.evaluate(({ BrowserWindow }) => { BrowserWindow.getAllWindows()[0].setSize(800, 640) })
  await expect.poll(() => page.evaluate(() => innerWidth)).toBeLessThanOrEqual(800)
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const compactLayout = await page.evaluate(() => ({ width: innerWidth, sidebar: document.querySelector('.sidebar').getBoundingClientRect().width, toolbarRight: document.querySelector('.toolbar-actions').getBoundingClientRect().right }))
  assert.ok(compactLayout.toolbarRight <= compactLayout.width + 1, JSON.stringify(compactLayout))
  await page.screenshot({ path: join(reportDir, 'compact.png') })
  assert.deepEqual(errors, [])
  checks.push('Delete cancellation and confirmation, document disappears from FTS, job history, no renderer errors')
  await writeFile(join(reportDir, 'desktop-report.json'), JSON.stringify({ at: new Date().toISOString(), checks, errors, tools: await desktop.evaluate(() => globalThis.libraryFixture.tools), limitations: ['Native picker and open-file responses use deterministic test doubles; actual packaged App, Core runtime, preload and EmbeddedAppView are exercised.', 'macOS executed; Windows was not executed.'] }, null, 2))
  console.log(JSON.stringify({ checks, reportDir }))
} catch (e) { await desktop.windows()[0]?.screenshot({ path: join(reportDir, 'failure.png') }); throw e }
finally { await desktop.evaluate(() => globalThis.libraryFixture?.cleanup()).catch(() => {}); await desktop.close(); if (temporary) await rm(temporary, { recursive: true, force: true }) }
